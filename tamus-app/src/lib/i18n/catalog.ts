const errorPrefixes = Object.entries(english)
  .filter(([key]) => key.includes('{e}'))
  .map(([key, value]) => ({ prefix: key.split('{e}')[0], value }));

export function translate(language: Locale, message: string, params: Parameters = {}): string {
  let text = message;
  if (language === 'en') {
    text = english[message] ?? message;
    if (text === message && !Object.hasOwn(english, message)) {
      const diagnostic = errorPrefixes.find(({ prefix }) => message.startsWith(prefix));
      if (diagnostic)
        text = diagnostic.value.replace('{e}', message.slice(diagnostic.prefix.length));
    }
  }
  // A replacement callback treats user-supplied $&, braces and markup literally.
  return text.replace(/\{(\w+)\}/g, (token, key: string) =>
    Object.hasOwn(params, key) ? String(params[key] ?? '') : token,
  );
}

const nouns = {
  model: { ru: ['модель', 'модели', 'моделей'], en: ['model', 'models'] },
  item: { ru: ['элемент', 'элемента', 'элементов'], en: ['item', 'items'] },
  block: { ru: ['блок', 'блока', 'блоков'], en: ['block', 'blocks'] },
  connection: { ru: ['связь', 'связи', 'связей'], en: ['connection', 'connections'] },
} as const;
export type CountNoun = keyof typeof nouns;
export function formatCount(language: Locale, noun: CountNoun, amount: number): string {
  const form = new Intl.PluralRules(language).select(amount);
  const index =
    form === 'one' ? 0 : language === 'ru' && form === 'few' ? 1 : language === 'ru' ? 2 : 1;
  return `${new Intl.NumberFormat(language).format(amount)} ${nouns[noun][language][index]}`;
}
